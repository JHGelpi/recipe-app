// Writes apps/mobile/src/whatsNew/releaseNotesText.ts from RELEASE_NOTES.md,
// so the web build carries the notes and they work offline (FR-47). Metro
// can't import a file from the repo root, so the copy is committed; a unit
// test fails when it is out of date. Run `pnpm release-notes` after editing.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SOURCE = fileURLToPath(new URL('../RELEASE_NOTES.md', import.meta.url));
export const OUT = fileURLToPath(
  new URL('../apps/mobile/src/whatsNew/releaseNotesText.ts', import.meta.url),
);

export function moduleFor(text) {
  return (
    '// Generated by scripts/release-notes.mjs from RELEASE_NOTES.md. Do not edit.\n' +
    `export const RELEASE_NOTES_TEXT = ${JSON.stringify(text)};\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, moduleFor(readFileSync(SOURCE, 'utf8')));
  console.log(`wrote ${OUT}`);
}
